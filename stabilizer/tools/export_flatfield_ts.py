"""Write web/src/tv/liveStab/flatfield.ts from skylight_stab/flatfield.npz (the live shader uses
the same per-zoom lens flat-field as the archive). Run from the repo root after changing the maps:

  python3 stabilizer/tools/export_flatfield_ts.py
"""
import base64
import os

import cv2
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "stabilizer", "skylight_stab", "flatfield.npz")
DST = os.path.join(ROOT, "web", "src", "tv", "liveStab", "flatfield.ts")
W, H, LO, STEP = 80, 45, 0.85, 0.001   # byte b -> gain LO + b * STEP (0.85 .. 1.105)

z = np.load(SRC)
keys = sorted(z.files, key=lambda k: float(k[1:]))
rows = []
for k in keys:
    m = cv2.resize(z[k].astype(np.float32), (W, H), interpolation=cv2.INTER_AREA)
    b = np.round((m - LO) / STEP)
    assert b.min() >= 0 and b.max() <= 255, (k, b.min(), b.max())
    rows.append(b.astype(np.uint8))
data = base64.b64encode(np.concatenate(rows).tobytes()).decode()
stops = ", ".join(k[1:] for k in keys)
with open(DST, "w") as f:
    f.write(f"""// GENERATED by stabilizer/tools/export_flatfield_ts.py from
// stabilizer/skylight_stab/flatfield.npz — do not edit by hand.
//
// Lens flat-field (vignette) per zoom stop: the median of thousands of plain-sky
// archive frames per stop, 1.0 over the frame's central 20%. {W}×{H} per map,
// stacked top to bottom in `stops` order; byte b = gain {LO} + b × {STEP}.

/** Calibrated zoom stops, lens units (= pose.zoomUnits / series.json zoom). */
export const FF_STOPS = [{stops}];
export const FF_W = {W};
export const FF_H = {H};
export const FF_LO = {LO};
export const FF_STEP = {STEP};
/** Below the widest stop the map fades to flat by this zoom (as the archive). */
export const FF_FADE_LO = 800;
export const FF_DATA = "{data}";
""")
print(DST, len(data), "chars")
